import { test, expect, chromium, type BrowserContext } from '@playwright/test';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildServer } from '../../dist/server/app.js';
import { loadConfig } from '../../dist/core/config.js';
import { openDatabase } from '../../dist/core/database.js';
import { ExtensionAuth } from '../../dist/core/extension-auth.js';
import { visualFixture } from '../../test/fixtures/visual';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
test('visual explanations work in Kindle, project chat and the PDF reader, including offline export and saved history', async ({}, info) => {
  const temporary = await mkdtemp(path.join(os.tmpdir(), 'pdfpal-visual-browser-'));
  const fixture = path.join(temporary, 'codex-fixture');
  const responseFile = path.join(temporary, 'visual-response.json');
  await writeFile(responseFile, JSON.stringify(visualFixture));
  await writeFile(fixture, `#!/usr/bin/env node\nconst fs=require('node:fs');const prompt=fs.readFileSync(0,'utf8');setTimeout(()=>process.stdout.write(prompt.startsWith("You are pdfpal's visual teacher.")?fs.readFileSync(${JSON.stringify(responseFile)},'utf8'):'# Attention\\n\\nAttention lets tokens combine context.'),150);`, { mode: 0o700 });
  const config = loadConfig({ dataDir: path.join(temporary, 'data'), agent: 'codex', codexBin: fixture });
  const app = await buildServer(config), db = openDatabase(config);
  let context: BrowserContext | undefined;
  try {
    await app.listen({ host: '127.0.0.1', port: 0 });
    const base = `http://127.0.0.1:${(app.server.address() as { port: number }).port}`;
    const project = (await app.inject({ method: 'POST', url: '/api/projects', payload: { title: 'Visual reading' } })).json();
    context = await chromium.launchPersistentContext(path.join(temporary, 'browser'), { channel: 'chromium', headless: true,
      ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}),
      args: [`--disable-extensions-except=${root}/dist`, `--load-extension=${root}/dist`], viewport: { width: 390, height: 850 } });
    const worker = context.serviceWorkers()[0] ?? await context.waitForEvent('serviceworker');
    const id = new URL(worker.url()).host;
    const reader = await context.newPage();
    await reader.route('https://read.amazon.com/**', route => route.fulfill({ contentType: 'text/html', body: '<title>Attention - Kindle</title><h1 data-testid="book-title">Attention</h1><p id="passage">Attention gives words context.</p>' }));
    await reader.goto('https://read.amazon.com/?asin=TESTBOOK01');
    const tabId = await worker.evaluate(async () => (await chrome.tabs.query({ url: 'https://read.amazon.com/*' }))[0].id!);
    const panel = await context.newPage();
    await panel.goto(`chrome-extension://${id}/panel.html?tabId=${tabId}`);
    await panel.getByRole('button', { name: 'Connection and settings', exact: true }).click();
    await panel.locator('#server-url').fill(base);
    await panel.locator('#pair-code').fill(new ExtensionAuth(db).pairCode().code);
    await panel.getByRole('button', { name: 'Connect', exact: true }).click();
    await expect(panel.locator('#question')).toBeEnabled();
    await expect(panel.locator('#question')).toHaveAttribute('placeholder', /\/visual/);
    await expect(panel.locator('#visual-mode')).toHaveCount(0);
    await panel.locator('#question').fill('/');
    await panel.getByRole('button', { name: /\/visual Visual explanation/ }).click();
    await expect(panel.locator('#question')).toHaveValue('/visual ');
    await panel.locator('#question').press('Enter');
    await expect(panel.locator('.chat-command-hint')).toContainText('attached selection');
    expect((db.prepare('SELECT COUNT(*) n FROM kindle_turns').get() as { n: number }).n).toBe(0);
    await panel.locator('#question').fill('/visual Explain attention visually.');
    await panel.getByRole('button', { name: 'Ask', exact: true }).click();
    const card = panel.locator('.visual-card').first();
    await expect(card).toBeVisible();
    const first = db.prepare('SELECT question,response_mode FROM kindle_turns ORDER BY rowid LIMIT 1').get() as { question: string; response_mode: string };
    expect(first).toEqual({ question: 'Explain attention visually.', response_mode: 'visual' });
    await expect(card.getByRole('heading', { name: visualFixture.title })).toBeVisible();
    await card.getByRole('button', { name: 'bank', exact: true }).click();
    await expect(card.locator('.visual-detail')).toContainText('token being updated');
    await card.getByRole('button', { name: 'Next step', exact: true }).click();
    await expect(card.getByRole('heading', { name: 'Give relevant context more weight' })).toBeVisible();
    await card.getByRole('button', { name: 'Expand', exact: true }).click();
    await expect(panel.locator('dialog[open]')).toBeVisible();
    await panel.getByRole('button', { name: 'Close visual explanation', exact: true }).click();
    await card.getByRole('button', { name: 'Save to project', exact: true }).click();
    await expect(card.getByRole('link', { name: 'Open saved note' })).toBeVisible();
    const downloadPromise = panel.waitForEvent('download');
    await card.getByRole('button', { name: 'Export HTML', exact: true }).click();
    const download = await downloadPromise, file = path.join(temporary, 'explanation.html'); await download.saveAs(file);
    const html = await readFile(file, 'utf8'); expect(html).toContain('Takeaways');
    const offline = await context.newPage(); const remote: string[] = [];
    offline.on('request', req => { if (/^https?:/.test(req.url())) remote.push(req.url()); });
    await offline.goto(`file://${file}`);
    await offline.getByRole('button', { name: 'Next', exact: true }).click();
    await expect(offline.locator('#counter')).toHaveText('2 / 3');
    expect(remote).toEqual([]);
    await panel.reload();
    await expect(panel.locator('.visual-card').getByRole('heading', { name: visualFixture.title })).toBeVisible();
    await panel.screenshot({ path: info.outputPath('kindle-visual.png'), fullPage: true });
    for (const width of [320, 390]) {
      await panel.setViewportSize({ width, height: 850 });
      expect(await panel.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      const box = await panel.locator('.visual-card').boundingBox(); expect(box!.width).toBeGreaterThan(width - 45);
      await expect(panel.locator('#question')).toBeInViewport();
    }
    await reader.locator('#passage').evaluate(element => { const range = document.createRange(); range.selectNodeContents(element); const selection = getSelection()!; selection.removeAllRanges(); selection.addRange(range); });
    await panel.getByRole('button', { name: 'Capture selection', exact: true }).click();
    await expect(panel.locator('#selection-banner')).toBeVisible();
    await panel.locator('#question').fill('/visual');
    await panel.locator('#question').press('Enter');
    await expect(panel.locator('.visual-card')).toHaveCount(2);
    await expect(panel.locator('.visual-card').last().getByRole('heading', { name: visualFixture.title })).toBeVisible();
    const selectedTurn = db.prepare('SELECT question,capture_json FROM kindle_turns ORDER BY rowid DESC LIMIT 1').get() as { question: string; capture_json: string };
    expect(selectedTurn.question).toBe('Explain the selected passage visually.');
    expect(JSON.parse(selectedTurn.capture_json).text).toBe('Attention gives words context.');
    await expect(panel.locator('#selection-banner')).toBeHidden();
    const web = await context.newPage(); await web.setViewportSize({ width: 1280, height: 900 });
    await web.goto(`${base}/projects/${project.id}/chat`);
    await expect(web.getByRole('checkbox', { name: /Visual explanation/ })).toHaveCount(0);
    await web.getByRole('textbox').fill('/visuality');
    await web.getByRole('textbox').press('Enter');
    await expect(web.locator('.chat-command-hint')).toContainText('Unknown command');
    expect((db.prepare('SELECT COUNT(*) n FROM visual_explanations').get() as { n: number }).n).toBe(2);
    await web.getByRole('textbox').fill('/vis');
    await web.getByRole('textbox').press('Tab');
    await expect(web.getByRole('textbox')).toHaveValue('/visual ');
    await web.getByRole('textbox').press('Enter');
    await expect(web.locator('.chat-command-hint')).toContainText('attached selection');
    await web.getByRole('textbox').fill('/visual Explain a general concept visually.');
    await web.getByRole('textbox').press('Enter');
    await expect(web.locator('.visual-card').getByRole('heading', { name: visualFixture.title })).toBeVisible();
    await web.reload();
    await expect(web.locator('.visual-card').getByRole('heading', { name: visualFixture.title })).toBeVisible();
    await web.locator('.visual-card').getByRole('button', { name: 'Save to project', exact: true }).click();
    await expect(web.getByRole('link', { name: 'Open saved note' })).toBeVisible();
    await web.screenshot({ path: info.outputPath('web-visual.png'), fullPage: true });
    const sourceResponse = await app.inject({ method: 'POST', url: `/api/projects/${project.id}/sources`, payload: { url: path.join(root, '../test/fixtures/sample.pdf'), title: 'Visual test PDF' } });
    expect(sourceResponse.statusCode).toBe(200); const source = sourceResponse.json();
    await web.goto(`${base}/projects/${project.id}/sources/${source.id}`);
    await expect(web.locator('[data-pdf-page="1"] canvas')).toBeVisible();
    const pdfText = web.locator('.react-pdf__Page__textContent span').first(); await expect(pdfText).toBeVisible();
    await web.getByRole('button', { name: '📝 Notes', exact: true }).click();
    await pdfText.evaluate(element => { const range = document.createRange(); range.selectNodeContents(element); const selection = getSelection()!; selection.removeAllRanges(); selection.addRange(range); document.dispatchEvent(new MouseEvent('mouseup', { bubbles: true, clientX: 200, clientY: 200 })); });
    await expect(web.locator('[data-ask-bubble]')).toBeVisible();
    await web.screenshot({ path: info.outputPath('pdf-selection-popup.png'), fullPage: true });
    await web.locator('[data-ask-bubble]').getByRole('button', { name: 'Explain visually', exact: true }).click();
    await expect(web.locator('.visual-card').getByRole('heading', { name: visualFixture.title })).toBeVisible();
    await web.reload();
    await expect(web.locator('.visual-card').getByRole('heading', { name: visualFixture.title })).toBeVisible();
    await web.screenshot({ path: info.outputPath('pdf-visual.png'), fullPage: true });
    const originalSelection = await pdfText.textContent();
    const selectedRequest = db.prepare('SELECT request_json FROM visual_explanations WHERE client_id IS NULL ORDER BY rowid DESC LIMIT 1').get() as { request_json: string };
    expect(JSON.parse(selectedRequest.request_json).input.selection).toBe(originalSelection);
    expect((db.prepare('SELECT COUNT(*) n FROM visual_explanations').get() as { n: number }).n).toBe(4);
    await pdfText.evaluate(element => { const range = document.createRange(); range.selectNodeContents(element); const selection = getSelection()!; selection.removeAllRanges(); selection.addRange(range); document.dispatchEvent(new MouseEvent('mouseup', { bubbles: true, clientX: 200, clientY: 200 })); });
    await web.locator('[data-ask-bubble]').getByRole('button', { name: /Ask/ }).click();
    await web.locator('textarea').fill('/visual');
    await web.locator('textarea').press('Enter');
    await expect(web.locator('.visual-card')).toHaveCount(2);
    await expect(web.locator('.visual-card').last().getByRole('heading', { name: visualFixture.title })).toBeVisible();
    await writeFile(responseFile, 'Not a valid visual explanation');
    await web.locator('textarea').fill('/visual Try another concept visually.');
    await web.locator('textarea').press('Enter');
    await expect(web.getByRole('button', { name: 'Retry visual explanation', exact: true })).toBeVisible();
    await writeFile(responseFile, JSON.stringify(visualFixture));
    await web.getByRole('button', { name: 'Retry visual explanation', exact: true }).click();
    await expect(web.locator('.visual-card').last().getByRole('heading', { name: visualFixture.title })).toBeVisible();
    await web.reload();
    await expect(web.locator('.visual-card')).toHaveCount(3);
    await expect(web.locator('.visual-card').last().getByRole('heading', { name: visualFixture.title })).toBeVisible();
    await web.locator('textarea').fill('Explain attention in text.');
    await web.locator('textarea').press('Enter');
    await expect(web.getByText('Attention lets tokens combine context.', { exact: true })).toBeVisible();
    await expect(web.getByRole('button', { name: 'Explain visually', exact: true })).toHaveCount(0);
    await web.locator('textarea').fill('/visual Explain attention in the previous answer.');
    await web.locator('textarea').press('Enter');
    await expect(web.locator('.visual-card')).toHaveCount(4);
    await expect(web.locator('.visual-card').last().getByRole('heading', { name: visualFixture.title })).toBeVisible();
    expect((db.prepare('SELECT COUNT(*) n FROM visual_explanations').get() as { n: number }).n).toBe(8);
  } finally { await context?.close(); await app.close(); db.close(); await rm(temporary, { recursive: true, force: true }); }
});
