// Writes src/core/sense-runtime-manifest.ts: the SHA-256 identity of every
// file the contextual-definitions worker loads from a user-provisioned
// runtime (onnxruntime-node with its native binaries for each platform,
// onnxruntime-common, and @huggingface/tokenizers).
//
//   node scripts/sense-runtime-manifest.mjs [node_modules directory]
//
// Run it after changing either pinned version in package.json. It reads only
// local files.
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const modules = path.resolve(process.argv[2] ?? path.join(root, 'node_modules'))
const pins = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).devDependencies
const packages = {
  'onnxruntime-node': pins['onnxruntime-node'],
  'onnxruntime-common': pins['onnxruntime-node'],
  '@huggingface/tokenizers': pins['@huggingface/tokenizers'],
}
const files = []
const add = (relative, platform) => {
  const bytes = fs.readFileSync(path.join(modules, relative))
  files.push({ path: relative.split(path.sep).join('/'), size: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex'), ...(platform ? { platform } : {}) })
}
for (const [name, version] of Object.entries(packages)) {
  const actual = JSON.parse(fs.readFileSync(path.join(modules, name, 'package.json'), 'utf8')).version
  if (actual !== version) throw new Error(`${name} is ${actual}, expected ${version}`)
  add(path.join(name, 'package.json'))
  for (const license of ['LICENSE', 'LICENSE.txt', 'ThirdPartyNotices.txt']) if (fs.existsSync(path.join(modules, name, license))) add(path.join(name, license))
}
for (const file of ['index.js', 'backend.js', 'binding.js', 'version.js']) add(path.join('onnxruntime-node', 'dist', file))
const binaries = path.join(modules, 'onnxruntime-node', 'bin', 'napi-v6')
for (const platform of fs.readdirSync(binaries).sort()) {
  for (const arch of fs.readdirSync(path.join(binaries, platform)).sort()) {
    for (const file of fs.readdirSync(path.join(binaries, platform, arch)).sort()) {
      // The Windows CPU binding only needs the runtime and its N-API addon.
      if (platform === 'win32' && !['onnxruntime.dll', 'onnxruntime_binding.node'].includes(file)) continue
      add(path.join('onnxruntime-node', 'bin', 'napi-v6', platform, arch, file), `${platform}-${arch}`)
    }
  }
}
const common = path.join(modules, 'onnxruntime-common', 'dist', 'cjs')
for (const file of fs.readdirSync(common).sort()) if (file.endsWith('.js') || file === 'package.json') add(path.join('onnxruntime-common', 'dist', 'cjs', file))
add(path.join('@huggingface', 'tokenizers', 'dist', 'tokenizers.cjs'))

const output = path.join(root, 'src', 'core', 'sense-runtime-manifest.ts')
fs.writeFileSync(output, `// Generated by scripts/sense-runtime-manifest.mjs. Do not edit by hand.
import type { RuntimeIdentity } from './sense-model.js'

export const SENSE_RUNTIME: RuntimeIdentity = ${JSON.stringify({
  name: `onnxruntime-node ${packages['onnxruntime-node']} with @huggingface/tokenizers ${packages['@huggingface/tokenizers']}`,
  packages,
  files,
}, null, 2)}
`)
console.log(`Wrote ${files.length} files to ${path.relative(root, output)}`)
