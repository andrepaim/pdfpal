"""Build the optional release ZIPs locally. The desktop installer does not run this script.

Usage after npm ci:
  python3 scripts/build-sense-downloads.py /path/to/pinned/export /path/to/output

The model and runtime manifests determine every executable payload byte. The
notices for ONNX Runtime come from the official onnxruntime 1.30.0 wheel.
Check generated pins into source before publishing these exact ZIPs. For a new
payload, use a new tag and preserve all previously published download URLs.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
NOTICES = ROOT / "scripts/sense-notices"
TAG = "dictionary-assets-v1"


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def build_zip(directory, name, files, notices):
    output = directory / name
    with tempfile.NamedTemporaryFile(dir=directory) as staged:
        with zipfile.ZipFile(staged, "w") as archive:
            entries = [(file["path"], path, file) for file, path in files]
            entries.extend(("notices/" + key, path, None) for key, path in notices.items())
            for member, path, pin in sorted(entries):
                if pin and (path.stat().st_size != pin["size"] or digest(path) != pin["sha256"]):
                    raise ValueError(f"File differs from pinned input: {member}")
                info = zipfile.ZipInfo(member, (1980, 1, 1, 0, 0, 0))
                info.create_system = 3
                info.external_attr = 0o100644 << 16
                info.compress_type = zipfile.ZIP_DEFLATED
                with archive.open(info, "w") as dst, path.open("rb") as src:
                    shutil.copyfileobj(src, dst, 1024 * 1024)
        staged.seek(0)
        with output.open("xb") as target:
            shutil.copyfileobj(staged, target, 1024 * 1024)
    return {"name": name, "size": output.stat().st_size, "sha256": digest(output)}


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument("model", type=Path)
    args.add_argument("output", type=Path)
    parsed = args.parse_args()
    parsed.output.mkdir(parents=True, exist_ok=True)
    js = """import { ETTIN_ENGLISH_INT8 } from './src/core/sense-model.ts';
import { SENSE_RUNTIME } from './src/core/sense-runtime-manifest.ts';
console.log(JSON.stringify([ETTIN_ENGLISH_INT8.files, SENSE_RUNTIME.files]));"""
    model_files, runtime_files = json.loads(subprocess.check_output(
        ["node", "--import", "tsx", "--input-type=module", "-e", js], cwd=ROOT
    ))
    modules = ROOT / "node_modules"
    model = build_zip(parsed.output, "ettin-150m-wsd-int8-v1.zip",
                      [(pin, parsed.model / pin["path"]) for pin in model_files],
                      {"MODEL.txt": NOTICES / "MODEL.txt",
                       "Apache-2.0.txt": modules / "@huggingface/tokenizers/LICENSE",
                       "Ettin-base-LICENSE.txt": NOTICES / "Ettin-base-LICENSE.txt"})
    runtime = {}
    for platform in ("linux-x64", "win32-x64"):
        files = [(dict(pin, path="node_modules/" + pin["path"]), modules / pin["path"])
                 for pin in runtime_files if pin.get("platform", platform) == platform]
        runtime[platform] = build_zip(parsed.output, f"sense-runtime-{platform}-v1.zip", files, {
            name: NOTICES / name for name in ("ONNX-Runtime-LICENSE.txt", "ONNX-Runtime-ThirdPartyNotices.txt")
        })
    manifest = ROOT / "src/core/sense-download-assets.ts"
    manifest.write_text("// Generated by scripts/build-sense-downloads.py from verified inputs.\n"
                        "export type SenseDownloadAsset = { name: string; size: number; sha256: string }\n"
                        f"export const SENSE_ASSET_TAG = '{TAG}'\n"
                        f"export const MODEL_DOWNLOAD: SenseDownloadAsset = {json.dumps(model, indent=2)}\n"
                        f"export const RUNTIME_DOWNLOADS: Record<string, SenseDownloadAsset> = {json.dumps(runtime, indent=2)}\n")
    print(manifest.read_text())


if __name__ == "__main__":
    main()
