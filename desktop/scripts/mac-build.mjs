// macOS counterpart of windows-m0.ps1: install locked dependencies, run the native tests, package an
// ad-hoc signed pdfpal.app, run it with the packaged smoke flag, then build the disk image and manifest.
// Run `npm ci` and `node desktop/scripts/stage.mjs` first. Only the exported planning functions run off a Mac.
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawn } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { buildConfiguration, builderArguments, builderEnvironment, configurationName, installerName, manifestName, resolveArch } from './build-installer.mjs'

const repositoryRoot = fileURLToPath(new URL('../../', import.meta.url))
export const smokeFlags = Object.freeze({ m0: '--m0-smoke', m2: '--m2-smoke' })
// A PATH without any separately installed Node, as the Windows driver uses System32 alone.
export const systemPath = '/usr/bin:/bin:/usr/sbin:/sbin'
export const usage = 'Usage: node desktop/scripts/mac-build.mjs [--source=<repo root>] [--work=<dir>] [--arch=arm64|x64] [--skip-install] [--smoke=m0|m2|none]'

export function parseArguments(argv, { tmpdir = os.tmpdir(), source = repositoryRoot } = {}) {
  const options = { source, work: path.join(tmpdir, 'pdfpal-mac-build'), arch: 'arm64', skipInstall: false, smoke: 'm0' }
  for (const argument of argv) {
    const match = /^--([a-z-]+)(?:=(.*))?$/s.exec(argument)
    if (!match) throw new Error(`Unexpected argument: ${argument}\n${usage}`)
    const [, name, value] = match
    const required = () => { if (!value) throw new Error(`--${name} needs a value\n${usage}`); return value }
    if (name === 'source') options.source = required()
    else if (name === 'work') options.work = required()
    else if (name === 'arch') options.arch = resolveArch('darwin', required())
    else if (name === 'smoke') {
      options.smoke = required()
      if (!['m0', 'm2', 'none'].includes(options.smoke)) throw new Error(`--smoke must be m0, m2 or none\n${usage}`)
    } else if (name === 'skip-install' && value === undefined) options.skipInstall = true
    else throw new Error(`Unknown option: ${argument}\n${usage}`)
  }
  return { ...options, source: path.resolve(options.source), work: path.resolve(options.work) }
}

// electron-builder writes x64 to artifacts/mac and every other architecture to artifacts/mac-<arch>.
export function appOutputDirectory(arch) { return resolveArch('darwin', arch) === 'x64' ? 'mac' : `mac-${arch}` }

export function buildPlan({ source, work, arch, skipInstall = false, smoke = 'm0' }, { version, executableName = 'pdfpal' }) {
  const tools = path.join(work, 'tools'), stage = path.join(work, 'stage'), artifacts = path.join(work, 'artifacts')
  const app = path.join(artifacts, appOutputDirectory(arch), `${executableName}.app`)
  return { source, work, arch, skipInstall, smoke, version, tools, stage, artifacts, app,
    executable: path.join(app, 'Contents/MacOS', executableName),
    launcher: path.join(app, 'Contents/Resources/bin/pdfpal'),
    launcherLink: path.join(work, 'cli-link/pdfpal'),
    config: path.join(work, configurationName('darwin', arch)),
    dmg: path.join(artifacts, installerName('darwin', version, arch)),
    manifest: path.join(artifacts, manifestName('darwin', arch)),
    receipt: path.join(work, 'packaged-receipt.json'),
    noNodeReceipt: path.join(work, 'no-system-node-receipt.json'),
    profile: path.join(work, 'smoke-profile'),
    cliData: path.join(work, 'cli-check'),
    settingsPreview: path.join(work, 'ai-settings.png'),
    fixture: path.join(work, 'fixture-provider'),
    providers: path.join(work, 'check-providers.mjs') }
}

/** What the driver copies into the work directory, as windows-m0.ps1 does. */
export function copyList(plan) {
  const desktop = path.join(plan.source, 'desktop')
  const entries = [
    { from: path.join(desktop, 'package.json'), to: path.join(plan.tools, 'package.json') },
    { from: path.join(desktop, 'package-lock.json'), to: path.join(plan.tools, 'package-lock.json') },
    { from: path.join(desktop, 'electron-builder.yml'), to: path.join(plan.work, 'electron-builder.yml') },
    { from: path.join(desktop, 'build'), to: path.join(plan.work, 'build') },
  ]
  const stage = path.join(desktop, 'stage')
  // node_modules is installed for this platform below; cli-bin is generated by build/prepare-cli.cjs.
  for (const name of fs.existsSync(stage) ? fs.readdirSync(stage).sort() : []) {
    if (!['node_modules', 'cli-bin'].includes(name)) entries.push({ from: path.join(stage, name), to: path.join(plan.stage, name) })
  }
  return entries
}

/** The deterministic assistant used by --smoke=m2: the shell twin of the C# fixture in windows-m0.ps1. */
export function fixtureProvider() {
  return `#!/bin/sh
# Deterministic test assistant for packaged acceptance. Never a real provider.
mode=\${PDFPAL_FIXTURE_MODE-}
case \${1-} in
  --version) echo '1.0.0 (Claude Code)'; exit 0 ;;
  --help) if [ "$mode" = unsupported ]; then echo 'old help'; else echo '--tools --strict-mcp-config --disallowedTools'; fi; exit 0 ;;
  auth)
    case $mode in
      signed_out) echo '{"loggedIn":false}' ;;
      api) echo '{"authMethod":"api_key","token":"SECRET"}' ;;
      unknown) echo 'unrecognized SECRET' ;;
      *) echo '{"loggedIn":true,"authMethod":"claude.ai"}' ;;
    esac
    exit 0 ;;
esac
if [ "$mode" = offline ]; then echo 'ECONNRESET token=SECRET' >&2; exit 1; fi
prompt=$(cat)
sleep 3
case $prompt in
  *'Reply exactly PDFPAL_CONNECTION_OK'*) echo 'PDFPAL_CONNECTION_OK' ;;
  *) echo 'M1 background answer' ;;
esac
`
}

/** Environment for the packaged smoke run; the same variables windows-m0.ps1 sets. */
export function smokeEnvironment(plan, env = process.env, { receipt = plan.receipt, path: searchPath } = {}) {
  const result = { ...env, PDFPAL_M0_RECEIPT: receipt, PDFPAL_M2_FAILURE_FIXTURE: plan.smoke === 'm2' ? '1' : '0', PDFPAL_M0_LIVE: '0', PDFPAL_M1_LIVE_CODEX: '0',
    PDFPAL_DESKTOP_PROFILE: plan.profile, PDFPAL_SETTINGS_PREVIEW: plan.settingsPreview }
  if (plan.smoke === 'm2') Object.assign(result, { CLAUDE_BIN: plan.fixture, PDFPAL_AGENT: 'claude' })
  if (searchPath !== undefined) result.PATH = searchPath
  return result
}

/** Every step in order. A step with `skip` is printed with its reason and not run. */
export function commandList(plan, { node = process.execPath, npm = 'npm', env = process.env } = {}) {
  const installSkip = plan.skipInstall ? '--skip-install: the locked dependencies are already installed in the work directory' : undefined
  const smokeSkip = plan.smoke === 'none' ? '--smoke=none was requested' : undefined
  const m2Skip = plan.smoke === 'm2' ? undefined : 'only with --smoke=m2'
  const cliEnv = { ...env, PDFPAL_DATA_DIR: plan.cliData, PDFPAL_DB: path.join(plan.cliData, 'pdfpal.db'), PDFPAL_DESKTOP_PROFILE: path.join(plan.cliData, 'profile') }
  delete cliEnv.PDFPAL_PORT
  const steps = [
    { id: 'install-tools', title: 'Install locked build tools', command: npm, args: ['ci', '--prefix', plan.tools, '--ignore-scripts', '--no-audit', '--no-fund'], skip: installSkip },
    { id: 'install-stage', title: 'Install locked runtime dependencies', command: npm, args: ['ci', '--prefix', plan.stage, '--omit=dev', '--ignore-scripts', '--no-audit', '--no-fund'], skip: installSkip },
    { id: 'notices', title: 'Write third-party notices', command: node, args: [path.join(plan.source, 'desktop/scripts/notices.mjs'), plan.stage, plan.source] },
    { id: 'discovery-test', title: 'Assistant discovery tests', command: node, args: [path.join(plan.stage, 'discovery.test.mjs')] },
    { id: 'runtime-test', title: 'Native process and ownership tests', command: node, args: [path.join(plan.stage, 'test/runtime.test.mjs')] },
    { id: 'setup-native', title: 'Native setup fixtures', skip: plan.smoke === 'm2'
      ? 'not applicable on macOS: test/setup-native.mjs asserts win32, a compiled fixture-provider.exe and the Windows registry PATH refresh. The macOS fixture assistant is exercised by the packaged --m2-smoke run instead.'
      : m2Skip },
    { id: 'setup-test', title: 'Setup state tests', command: node, args: ['--test', path.join(plan.stage, 'test/setup.test.mjs')], env: smokeEnvironment(plan, env), skip: m2Skip },
    { id: 'package', title: `Package pdfpal.app (${plan.arch})`, command: node, args: builderArguments({ tools: plan.tools, project: plan.work, config: plan.config, platform: 'darwin', arch: plan.arch, dir: true }),
      env: builderEnvironment('darwin', false, env) },
    { id: 'launcher-present', title: 'CLI launcher is bundled and executable', check: 'launcher' },
    { id: 'codesign-verify', title: 'Verify the ad-hoc signature', command: 'codesign', args: ['--verify', '--deep', '--strict', '--verbose=2', plan.app] },
    { id: 'codesign-adhoc', title: 'Confirm the identity is ad-hoc', command: 'codesign', args: ['--display', '--verbose=2', plan.app], expect: { stream: 'stderr', pattern: /^Signature=adhoc$/m, message: 'pdfpal.app is not ad-hoc signed' } },
    { id: 'launcher-version', title: 'CLI launcher runs the bundled runtime through a symlink', command: plan.launcherLink, args: ['--version'], env: cliEnv, timeoutMs: 60000,
      expect: { stream: 'stdout', pattern: new RegExp(`^${plan.version.replaceAll('.', '\\.')}\\s*$`), message: 'The bundled CLI did not report the desktop version' } },
    { id: 'smoke', title: `Packaged smoke run (${smokeFlags[plan.smoke] ?? 'none'})`, command: plan.executable, args: [smokeFlags[plan.smoke]].filter(Boolean),
      env: smokeEnvironment(plan, env), timeoutMs: 300000, receipt: plan.receipt, skip: smokeSkip },
    // Prove the packaged runtime does not depend on a separately installed Node.
    { id: 'smoke-no-system-node', title: 'Packaged smoke run without Node on PATH', command: plan.executable, args: [smokeFlags[plan.smoke]].filter(Boolean),
      env: { ...smokeEnvironment(plan, env, { receipt: plan.noNodeReceipt, path: systemPath }), PDFPAL_M0_LIVE: '0', PDFPAL_M1_LIVE_CODEX: '0' }, timeoutMs: 180000, receipt: plan.noNodeReceipt, check: 'no-system-node', skip: smokeSkip },
    // Provider diagnostics use the same compiled adapter, under the system Node.
    { id: 'providers', title: 'Assistant diagnostics', command: node, args: [plan.providers], cwd: plan.work, env: plan.smoke === 'm2' ? smokeEnvironment(plan, env) : env },
    { id: 'codesign-after-smoke', title: 'Signature still valid after the smoke run', command: 'codesign', args: ['--verify', '--deep', '--strict', plan.app] },
    { id: 'disk-image', title: 'Build the disk image and release manifest', command: node,
      args: [path.join(plan.source, 'desktop/scripts/build-installer.mjs'), '--platform=darwin', `--arch=${plan.arch}`, `--project=${plan.work}`, `--tools=${plan.tools}`, `--prepackaged=${plan.app}`] },
    { id: 'disk-image-verify', title: 'Verify the disk image checksum', command: 'hdiutil', args: ['verify', plan.dmg] },
    { id: 'manifest', title: 'Check the release manifest', check: 'manifest' },
  ]
  return steps.map(step => step.skip ? { id: step.id, title: step.title, skip: step.skip } : step)
}

/** Reasons the driver cannot run here; empty when it can. */
export function preflight(plan, { platform = process.platform, hostArch = process.arch } = {}) {
  const problems = []
  if (platform !== 'darwin') problems.push(`mac-build.mjs runs only on macOS (this is ${platform}). It needs codesign, hdiutil and a Mac to run the packaged app. On Windows use desktop/scripts/windows-m0.ps1.`)
  else if (hostArch !== plan.arch) problems.push(`This Mac is ${hostArch}; build ${plan.arch} on a ${plan.arch} Mac (for x64, a macos-15-intel runner). The native tests and the smoke run need the target architecture.`)
  if (!fs.existsSync(path.join(plan.source, 'desktop/stage/package.json'))) problems.push(`No staged desktop app in ${path.join(plan.source, 'desktop/stage')}. Run \`npm ci\` and \`node desktop/scripts/stage.mjs\` first.`)
  return problems
}

/** Check the manifest written next to the disk image against the release contract. */
export function checkManifest(manifest, plan, size) {
  const expected = { format: 1, appId: 'io.pdfpal.desktop', version: plan.version, platform: 'darwin', arch: plan.arch, signed: false, publisher: null, installer: path.basename(plan.dmg) }
  const keys = ['format', 'appId', 'version', 'platform', 'arch', 'signed', 'publisher', 'installer', 'sha256', 'size']
  if (JSON.stringify(Object.keys(manifest)) !== JSON.stringify(keys)) throw new Error(`Release manifest keys differ: ${Object.keys(manifest).join(', ')}`)
  for (const [key, value] of Object.entries(expected)) if (manifest[key] !== value) throw new Error(`Release manifest ${key} is ${JSON.stringify(manifest[key])}, expected ${JSON.stringify(value)}`)
  if (!/^[a-f0-9]{64}$/.test(manifest.sha256) || manifest.size !== size) throw new Error('Release manifest hash or size does not match the disk image')
  return manifest
}

/** Check a packaged smoke receipt: the app writes it, and it must describe this platform and architecture. */
export function checkReceipt(receipt, plan) {
  if (receipt.status !== 'passed') throw new Error(`Packaged smoke status is ${receipt.status}`)
  if (receipt.platform !== 'darwin' || receipt.arch !== plan.arch) throw new Error(`Packaged smoke ran as ${receipt.platform}/${receipt.arch}, expected darwin/${plan.arch}`)
  if (!Array.isArray(receipt.checks) || receipt.checks.length === 0) throw new Error('Packaged smoke receipt lists no checks')
  return receipt
}

function prepare(plan) {
  fs.mkdirSync(plan.tools, { recursive: true }); fs.mkdirSync(plan.stage, { recursive: true })
  for (const { from, to } of copyList(plan)) fs.cpSync(from, to, { recursive: true, force: true })
  fs.writeFileSync(plan.config, JSON.stringify(buildConfiguration(plan.work, { version: plan.version, platform: 'darwin' }), null, 2))
  // The provider check expects ../../dist from its original repository location.
  const providers = fs.readFileSync(path.join(plan.source, 'desktop/scripts/check-providers.mjs'), 'utf8')
  fs.writeFileSync(plan.providers, providers.replace('../../dist/core/', './stage/dist/core/'))
  if (plan.smoke === 'm2') { fs.writeFileSync(plan.fixture, fixtureProvider(), { mode: 0o755 }); fs.chmodSync(plan.fixture, 0o755) }
  for (const file of [plan.receipt, plan.noNodeReceipt, plan.manifest]) fs.rmSync(file, { force: true })
  fs.rmSync(plan.cliData, { recursive: true, force: true }); fs.mkdirSync(plan.cliData, { recursive: true })
}

function run(step, cwd) {
  return new Promise((resolve, reject) => {
    const capture = Boolean(step.expect)
    const child = spawn(step.command, step.args, { cwd: step.cwd ?? cwd, env: step.env ?? process.env, detached: Boolean(step.timeoutMs), stdio: capture ? ['ignore', 'pipe', 'pipe'] : 'inherit' })
    const output = { stdout: '', stderr: '' }
    if (capture) for (const stream of ['stdout', 'stderr']) child[stream].on('data', chunk => { output[stream] += chunk; process[stream].write(chunk) })
    let timedOut = false
    const timer = step.timeoutMs && setTimeout(() => { timedOut = true; try { process.kill(-child.pid, 'SIGKILL') } catch { child.kill('SIGKILL') } }, step.timeoutMs)
    child.once('error', error => { clearTimeout(timer); reject(new Error(`${step.title}: ${error.message}`)) })
    child.once('exit', (code, signal) => {
      clearTimeout(timer)
      if (timedOut) return reject(new Error(`${step.title} timed out`))
      if (code !== 0) return reject(new Error(`${step.title} failed with ${signal ?? `exit code ${code}`}`))
      if (capture && !step.expect.pattern.test(output[step.expect.stream])) return reject(new Error(step.expect.message))
      resolve()
    })
  })
}

async function check(step, plan) {
  if (step.check === 'launcher') {
    const stat = fs.statSync(plan.launcher)
    if (!stat.isFile() || (stat.mode & 0o111) !== 0o111) throw new Error(`${plan.launcher} is missing or not executable`)
    fs.rmSync(path.dirname(plan.launcherLink), { recursive: true, force: true }); fs.mkdirSync(path.dirname(plan.launcherLink), { recursive: true })
    fs.symlinkSync(plan.launcher, plan.launcherLink)
  } else if (step.check === 'manifest') {
    const manifest = checkManifest(JSON.parse(fs.readFileSync(plan.manifest, 'utf8')), plan, fs.statSync(plan.dmg).size)
    console.log(JSON.stringify(manifest, null, 2))
  }
}

async function main() {
  const options = parseArguments(process.argv.slice(2))
  const version = fs.existsSync(path.join(options.source, 'desktop/stage/package.json')) ? JSON.parse(fs.readFileSync(path.join(options.source, 'desktop/stage/package.json'), 'utf8')).version : '0.0.0'
  const plan = buildPlan(options, { version })
  const problems = preflight(plan)
  if (problems.length) { for (const problem of problems) console.error(problem); process.exit(1) }
  prepare(plan)
  for (const step of commandList(plan)) {
    if (step.skip) { console.log(`\n== SKIPPED ${step.id}: ${step.skip}`); continue }
    console.log(`\n== ${step.title}`)
    if (step.check === 'no-system-node') {
      const found = systemPath.split(':').find(directory => fs.existsSync(path.join(directory, 'node')))
      if (found) throw new Error(`Node is still discoverable in the restricted PATH (${found}/node)`)
    }
    if (step.receipt) fs.rmSync(step.receipt, { force: true })
    if (step.id.startsWith('smoke')) fs.rmSync(plan.profile, { recursive: true, force: true })
    if (step.command) await run(step, plan.work)
    else await check(step, plan)
    if (step.receipt) {
      if (!fs.existsSync(step.receipt)) throw new Error('Packaged smoke receipt missing')
      const text = fs.readFileSync(step.receipt, 'utf8')
      console.log(text)
      checkReceipt(JSON.parse(text), plan)
      fs.rmSync(plan.profile, { recursive: true, force: true })
    }
  }
  console.log(`\nDisk image: ${plan.dmg}\nManifest: ${plan.manifest}\nApplication: ${plan.app}\nDesktop evidence: ${plan.work}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { await main() } catch (error) { console.error(`mac-build failed: ${error.message}`); process.exit(1) }
}
